CREATE TABLE IF NOT EXISTS categories (
  categoryid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid BIGINT REFERENCES users(userid) ON DELETE CASCADE,  -- NULL = system default
  parent_categoryid BIGINT REFERENCES categories(categoryid) ON DELETE SET NULL,
  name VARCHAR(100) NOT NULL,
  icon VARCHAR(50)
);

CREATE UNIQUE INDEX categories_user_name_uq
    ON categories (userid, parent_categoryid, LOWER(name)) NULLS NOT DISTINCT;