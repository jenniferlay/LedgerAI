-- ===== categories =====

CREATE TABLE categories (
  categoryid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid BIGINT NOT NULL REFERENCES users(userid) ON DELETE CASCADE,  -- 0 = global
  parent_categoryid BIGINT,
  name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
  icon VARCHAR(50),

  UNIQUE (categoryid, userid),

  FOREIGN KEY (parent_categoryid, userid)
    REFERENCES categories (categoryid, userid)
    ON DELETE SET NULL (parent_categoryid),

  UNIQUE NULLS NOT DISTINCT (userid, parent_categoryid, name)
);

-- General must be inserted first: expenses/plaid_transactions default to categoryid 1
