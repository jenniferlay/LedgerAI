-- ===== expenses =====

CREATE TABLE expenses (
  expenseid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid BIGINT NOT NULL REFERENCES users(userid) ON DELETE CASCADE,
  categoryid BIGINT,
  category_userid BIGINT,  -- owner of the category: this user or 0 (global)
  amount NUMERIC(14, 2) NOT NULL CHECK (amount <> 0),
  note TEXT NOT NULL CHECK (length(btrim(note)) > 0),
  merchant VARCHAR(255),
  spent_on DATE NOT NULL DEFAULT CURRENT_DATE,

  CHECK ((categoryid IS NULL) = (category_userid IS NULL)),
  CHECK (category_userid IN (userid, 0)),

  FOREIGN KEY (categoryid, category_userid)
    REFERENCES categories (categoryid, userid)
    ON DELETE SET NULL (categoryid, category_userid)
);

CREATE INDEX ix_expenses_user_spent
  ON expenses (userid, spent_on DESC, expenseid DESC);

-- ===== plaid =====

CREATE TABLE plaid_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(userid) ON DELETE CASCADE,
    item_id VARCHAR(255) NOT NULL UNIQUE,
    access_token TEXT NOT NULL,
    cursor TEXT,
    sync_started_at TIMESTAMPTZ,
    requires_reauth BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_plaid_items_user
    ON plaid_items (user_id);

CREATE TABLE plaid_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plaid_item_id BIGINT NOT NULL REFERENCES plaid_items(id) ON DELETE CASCADE,
    transaction_id VARCHAR(255) NOT NULL,
    account_id VARCHAR(255) NOT NULL,
    pending_transaction_id VARCHAR(255),
    amount NUMERIC(14, 2) NOT NULL,
    transaction_date DATE NOT NULL,
    authorized_date DATE,
    name TEXT NOT NULL,
    merchant_name VARCHAR(255),
    pending BOOLEAN NOT NULL,
    iso_currency_code VARCHAR(3),
    unofficial_currency_code VARCHAR(10),
    plaid_category_detailed VARCHAR(100),
    user_merchant VARCHAR(255),
    user_note TEXT,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,

    -- User override only; NULL means use the stored Plaid category code.
    -- Owner is the item's user or 0 (global).
    categoryid BIGINT,
    category_userid BIGINT,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_plaid_transactions_item_transaction
        UNIQUE (plaid_item_id, transaction_id),

    CONSTRAINT ck_plaid_tx_category_pair
        CHECK ((categoryid IS NULL) = (category_userid IS NULL)),

    CONSTRAINT fk_plaid_tx_category
        FOREIGN KEY (categoryid, category_userid)
        REFERENCES categories (categoryid, userid)
        ON DELETE SET NULL (categoryid, category_userid)
);

CREATE INDEX ix_plaid_transactions_item_date
    ON plaid_transactions (plaid_item_id, transaction_date DESC, id DESC);

-- ===== budgets =====

-- One monthly budget per category per user.
CREATE TABLE budgets (
  budgetid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid BIGINT NOT NULL REFERENCES users(userid) ON DELETE CASCADE,
  categoryid BIGINT NOT NULL,
  category_userid BIGINT NOT NULL,          -- owner of the category: this user or 0 (global)
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CHECK (category_userid IN (userid, 0)),

  FOREIGN KEY (categoryid, category_userid)
    REFERENCES categories (categoryid, userid)
    ON DELETE CASCADE,

  UNIQUE (userid, categoryid, category_userid)
);

CREATE INDEX ix_budgets_user ON budgets (userid);

