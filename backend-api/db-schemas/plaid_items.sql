CREATE TABLE IF NOT EXISTS plaid_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(userid) ON DELETE CASCADE,
    item_id VARCHAR(255) NOT NULL UNIQUE,
    access_token TEXT NOT NULL,
    cursor TEXT,
    sync_in_progress BOOLEAN NOT NULL DEFAULT FALSE,
    requires_reauth BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE plaid_items
    ADD COLUMN IF NOT EXISTS sync_in_progress BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS requires_reauth BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS ix_plaid_items_user
    ON plaid_items (user_id);

CREATE TABLE IF NOT EXISTS plaid_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plaid_item_id BIGINT NOT NULL REFERENCES plaid_items(id) ON DELETE CASCADE,
    transaction_id VARCHAR(255) NOT NULL,
    account_id VARCHAR(255) NOT NULL,
    pending_transaction_id VARCHAR(255),
    amount NUMERIC(14, 2) NOT NULL,
    transaction_date DATE NOT NULL,
    authorized_date DATE,
    name TEXT NOT NULL,
    merchant_name VARCHAR(255),
    pending BOOLEAN NOT NULL,
    iso_currency_code VARCHAR(3),
    unofficial_currency_code VARCHAR(10),
    raw_data JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_plaid_transactions_item_transaction
        UNIQUE (plaid_item_id, transaction_id)
);

ALTER TABLE plaid_transactions
    ADD COLUMN IF NOT EXISTS category_id BIGINT REFERENCES categories(category_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS ix_plaid_transactions_item_date
    ON plaid_transactions (plaid_item_id, transaction_date DESC, id DESC);
